WIKI_RE = re.compile(r"(!?)\[\[([^\]]+)\]\]")
OBSIDIAN_URI_RE = re.compile(r"\[[^\]]+\]\((obsidian://open\?[^)]+)\)")
HEADING_RE = re.compile(r"^#{1,6}[ \t]+(.+?)\s*$", re.MULTILINE)
CONTROL_RE = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")


def sha256_path(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def rel_to(path: Path, root: Path) -> str:
    return path.relative_to(root).as_posix()


def load_manifest() -> dict | None:
    for path in (INTERNAL_MANIFEST, DIAGNOSTICS_MANIFEST):
        if path.is_file():
            return json.loads(path.read_text(encoding="utf-8"))
    return None


def verify_hashes(root: Path, items: dict[str, str], kind: str) -> list[str]:
    errors: list[str] = []
    for name, expected in items.items():
        path = root / name
        if not path.is_file():
            errors.append(f"missing_{kind}:{name}")
        elif sha256_path(path) != expected:
            errors.append(f"{kind}_hash_mismatch:{name}")
    return errors


def verify_assets() -> list[str]:
    errors = verify_hashes(DIAGNOSTICS_ROOT, DIAGNOSTICS_ASSETS, "asset")
    try:
        from PIL import Image
    except ImportError:
        return errors + ["pillow_missing_for_image_decode_check"]
    for name in DIAGNOSTICS_ASSETS:
        path = DIAGNOSTICS_ROOT / name
        if not path.is_file():
            continue
        try:
            with Image.open(path) as image:
                image.verify()
        except Exception as exc:
            errors.append(f"asset_decode_failed:{name}:{exc}")
    return errors


def output_specs() -> list[tuple[str, Path, dict[str, str], Path]]:
    return [
        ("internal", INTERNAL_ROOT, INTERNAL_FILES, INTERNAL_TOPIC_ROOT),
        ("diagnostics", DIAGNOSTICS_ROOT, DIAGNOSTICS_FILES, DIAGNOSTICS_TOPIC_ROOT),
    ]


def output_key(label: str, path: Path, root: Path) -> str:
    return f"{label}:{rel_to(path, root)}"


def protect_outputs(manifest: dict | None) -> list[str]:
    errors: list[str] = []
    registered = (manifest or {}).get("outputs", {})
    for label, root, desired_files, topic_root in output_specs():
        existing = {p.name for p in topic_root.iterdir() if p.is_file()} if topic_root.exists() else set()
        for name in sorted(existing - set(desired_files)):
            errors.append(f"unregistered_output:{label}:{name}")
        for name, desired in desired_files.items():
            path = topic_root / name
            if not path.exists() or path.read_text(encoding="utf-8") == desired:
                continue
            if manifest is None and path.read_text(encoding="utf-8") in {"", "\n"}:
                # apply_patch may create an empty expected file solely to scaffold
                # a directory that the restricted runtime cannot mkdir itself.
                continue
            prior = registered.get(output_key(label, path, root), {}).get("sha256")
            if not prior or sha256_path(path) != prior:
                errors.append(f"manual_edit_conflict:{label}:{name}")
    return errors


def ensure_index_block(
    path: Path,
    baseline: str,
    start_marker: str,
    end_marker: str,
    block: str,
    anchor: str,
    write: bool,
) -> tuple[list[str], bool]:
    text = path.read_text(encoding="utf-8")
    starts, ends = text.count(start_marker), text.count(end_marker)
    if starts == 1 and ends == 1:
        start = text.index(start_marker)
        end = text.index(end_marker, start) + len(end_marker)
        return ([] if text[start:end] == block else [f"index_block_manual_edit:{path}"], False)
    if starts or ends:
        return [f"index_marker_mismatch:{path}"], False
    if not write:
        return [f"index_block_missing:{path}"], False
    if sha256_path(path) != baseline:
        return [f"index_baseline_changed:{path}"], False
    if text.count(anchor) != 1:
        return [f"index_anchor_not_unique:{path}"], False
    path.write_text(text.replace(anchor, f"{block}\n\n{anchor}", 1), encoding="utf-8", newline="\n")
    return [], True


def ensure_indexes(write: bool) -> tuple[list[str], list[str]]:
    errors: list[str] = []
    changed: list[str] = []
    checks = [
        (
            INTERNAL_INDEX,
            INTERNAL_INDEX_BASELINE,
            INTERNAL_INDEX_START,
            INTERNAL_INDEX_END,
            INTERNAL_INDEX_BLOCK,
            "## 总目录",
            "internal",
        ),
        (
            DIAGNOSTICS_INDEX,
            DIAGNOSTICS_INDEX_BASELINE,
            DIAGNOSTICS_INDEX_START,
            DIAGNOSTICS_INDEX_END,
            DIAGNOSTICS_INDEX_BLOCK,
            "| 顺序 | 篇 | 类型 | 文件 | PDF 物理页 |",
            "diagnostics",
        ),
    ]
    for path, baseline, start, end, block, anchor, label in checks:
        item_errors, item_changed = ensure_index_block(path, baseline, start, end, block, anchor, write)
        errors.extend(item_errors)
        if item_changed:
            changed.append(f"{label}:{path.name}")
    return errors, changed


def write_outputs() -> list[str]:
    changed: list[str] = []
    for label, root, desired_files, topic_root in output_specs():
        topic_root.mkdir(parents=True, exist_ok=True)
        for name, desired in desired_files.items():
            path = topic_root / name
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != desired:
                path.write_text(desired, encoding="utf-8", newline="\n")
                changed.append(output_key(label, path, root))
    return changed


def resolve_wikilink(source: Path, root: Path, raw: str) -> tuple[Path, str | None]:
    target = raw.split("|", 1)[0].strip()
    path_text, anchor = (target.split("#", 1) + [None])[:2] if "#" in target else (target, None)
    if not path_text:
        path = source
    elif "/" in path_text:
        path = root / path_text
    else:
        path = source.parent / path_text
    if not path.suffix:
        path = path.with_suffix(".md")
    return path, anchor


def verify_links() -> tuple[list[str], int, int, int]:
    errors: list[str] = []
    wikilinks = 0
    cross_links = 0
    embedded_images = 0
    vault_roots = {"01_41内科学": INTERNAL_ROOT, "01_32_诊断学_副本": DIAGNOSTICS_ROOT}
    for label, root, desired_files, topic_root in output_specs():
        for name in desired_files:
            source = topic_root / name
            text = source.read_text(encoding="utf-8")
            for match in WIKI_RE.finditer(text):
                embedded, raw = match.groups()
                target, anchor = resolve_wikilink(source, root, raw)
                wikilinks += 1
                embedded_images += int(bool(embedded))
                if not target.is_file():
                    errors.append(f"broken_wikilink:{label}:{name}:{raw}")
                    continue
                if anchor:
                    headings = {
                        value.strip().rstrip("#").rstrip()
                        for value in HEADING_RE.findall(target.read_text(encoding="utf-8"))
                    }
                    if anchor not in headings:
                        errors.append(f"broken_anchor:{label}:{name}:{raw}")
            for uri in OBSIDIAN_URI_RE.findall(text):
                parsed = urlparse(uri)
                query = parse_qs(parsed.query)
                vault = query.get("vault", [""])[0]
                file_path = query.get("file", [""])[0]
                target_root = vault_roots.get(vault)
                target = (target_root / file_path).with_suffix(".md") if target_root else None
                cross_links += 1
                if target is None or not target.is_file():
                    errors.append(f"broken_cross_vault_uri:{label}:{name}:{uri}")
    return errors, wikilinks, cross_links, embedded_images


def verify_outputs(manifest: dict | None) -> list[str]:
    errors: list[str] = []
    registered = (manifest or {}).get("outputs", {})
    for label, root, desired_files, topic_root in output_specs():
        actual_names = {p.name for p in topic_root.iterdir() if p.is_file()} if topic_root.exists() else set()
        for name in sorted(set(desired_files) - actual_names):
            errors.append(f"missing_output:{label}:{name}")
        for name in sorted(actual_names - set(desired_files)):
            errors.append(f"unexpected_output:{label}:{name}")
        for name, desired in desired_files.items():
            path = topic_root / name
            if not path.is_file():
                continue
            actual = path.read_text(encoding="utf-8")
            if actual != desired:
                errors.append(f"output_content_mismatch:{label}:{name}")
            if "\ufffd" in actual:
                errors.append(f"replacement_character:{label}:{name}")
            if CONTROL_RE.search(actual):
                errors.append(f"control_character:{label}:{name}")
            key = output_key(label, path, root)
            if not manifest:
                continue
            expected_hash = registered.get(key, {}).get("sha256")
            if not expected_hash:
                errors.append(f"manifest_output_missing:{key}")
            elif sha256_path(path) != expected_hash:
                errors.append(f"manifest_hash_mismatch:{key}")
    if manifest is None:
        errors.append("manifest_missing")
    return errors


def describe_text_file(path: Path) -> dict:
    return {
        "sha256": sha256_path(path),
        "bytes": path.stat().st_size,
        "lines": len(path.read_text(encoding="utf-8").splitlines()),
    }


def describe_binary_file(path: Path) -> dict:
    return {
        "sha256": sha256_path(path),
        "bytes": path.stat().st_size,
    }


def build_manifest() -> dict:
    from PIL import Image

    outputs: dict[str, dict] = {}
    for label, root, desired_files, topic_root in output_specs():
        for name in sorted(desired_files):
            path = topic_root / name
            outputs[output_key(label, path, root)] = describe_text_file(path)
    sources = {"internal": {}, "diagnostics": {}}
    for name in INTERNAL_SOURCES:
        sources["internal"][name] = describe_text_file(INTERNAL_ROOT / name)
    for name in DIAGNOSTICS_SOURCES:
        sources["diagnostics"][name] = describe_text_file(DIAGNOSTICS_ROOT / name)
    assets = {}
    for name in DIAGNOSTICS_ASSETS:
        path = DIAGNOSTICS_ROOT / name
        with Image.open(path) as image:
            dimensions = [image.width, image.height]
        assets[name] = {**describe_binary_file(path), "dimensions": dimensions}
    return {
        "schema": "hematology-diagnostics-bridge/v1",
        "generated_on": GENERATED_ON,
        "source_scope": "本地内科学第10版血液病21章 + 诊断学第10版13章；无外部指南",
        "roots": {"internal": str(INTERNAL_ROOT), "diagnostics": str(DIAGNOSTICS_ROOT)},
        "navigation": {
            "internal": {"path": rel_to(INTERNAL_INDEX, INTERNAL_ROOT), "sha256": sha256_path(INTERNAL_INDEX)},
            "diagnostics": {"path": rel_to(DIAGNOSTICS_INDEX, DIAGNOSTICS_ROOT), "sha256": sha256_path(DIAGNOSTICS_INDEX)},
        },
        "sources": sources,
        "assets": assets,
        "outputs": outputs,
        "validation": {
            "expected_markdown_files": len(INTERNAL_FILES) + len(DIAGNOSTICS_FILES),
            "expected_sources": len(INTERNAL_SOURCES) + len(DIAGNOSTICS_SOURCES),
            "expected_images": len(DIAGNOSTICS_ASSETS),
            "source_files_read_only": True,
            "manual_edits_protected": True,
            "williams_and_old_manual_topics_untouched": True,
        },
    }


def write_manifests() -> list[str]:
    desired = json.dumps(build_manifest(), ensure_ascii=False, indent=2) + "\n"
    changed: list[str] = []
    for label, path in (("internal", INTERNAL_MANIFEST), ("diagnostics", DIAGNOSTICS_MANIFEST)):
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != desired:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(desired, encoding="utf-8", newline="\n")
            changed.append(label)
    return changed


def verify_manifest_mirror() -> list[str]:
    if not INTERNAL_MANIFEST.is_file() or not DIAGNOSTICS_MANIFEST.is_file():
        return ["manifest_mirror_missing"]
    if INTERNAL_MANIFEST.read_bytes() != DIAGNOSTICS_MANIFEST.read_bytes():
        return ["manifest_mirror_mismatch"]
    return []


def run(write: bool) -> int:
    errors = []
    errors += verify_hashes(INTERNAL_ROOT, INTERNAL_SOURCES, "internal_source")
    errors += verify_hashes(DIAGNOSTICS_ROOT, DIAGNOSTICS_SOURCES, "diagnostics_source")
    errors += verify_assets()
    manifest = load_manifest()
    if write:
        errors += protect_outputs(manifest)
    if errors:
        print("ERROR Source/asset/protection conflict; no write performed:")
        for item in errors:
            print(f"- {item}")
        return 1

    index_errors, index_changed = ensure_indexes(write)
    if index_errors:
        print("ERROR Navigation conflict:")
        for item in index_errors:
            print(f"- {item}")
        return 1

    changed_files: list[str] = []
    manifest_changed: list[str] = []
    if write:
        changed_files = write_outputs()
        manifest_changed = write_manifests()
        manifest = load_manifest()

    errors = []
    errors += verify_hashes(INTERNAL_ROOT, INTERNAL_SOURCES, "internal_source")
    errors += verify_hashes(DIAGNOSTICS_ROOT, DIAGNOSTICS_SOURCES, "diagnostics_source")
    errors += verify_assets()
    errors += verify_outputs(manifest)
    errors += verify_manifest_mirror()
    index_errors, _ = ensure_indexes(False)
    errors += index_errors
    link_errors, wikilinks, cross_links, embedded_images = verify_links()
    errors += link_errors
    if embedded_images != len(DIAGNOSTICS_ASSETS):
        errors.append(f"embedded_image_count:{embedded_images}!={len(DIAGNOSTICS_ASSETS)}")
    if wikilinks < 100:
        errors.append(f"wikilink_count_too_low:{wikilinks}")
    if cross_links < 30:
        errors.append(f"cross_vault_link_count_too_low:{cross_links}")

    if errors:
        print("VERIFY_FAILED")
        for item in errors:
            print(f"- {item}")
        return 1

    if write:
        print(
            "WRITE_OK "
            f"changed_files={len(changed_files)} "
            f"index_changed={len(index_changed)} "
            f"manifest_changed={len(manifest_changed)}"
        )
    print(
        "HEMATOLOGY_DIAGNOSTICS_BRIDGE_VERIFY_OK "
        f"internal_files={len(INTERNAL_FILES)} diagnostics_files={len(DIAGNOSTICS_FILES)} "
        f"sources={len(INTERNAL_SOURCES) + len(DIAGNOSTICS_SOURCES)} "
        f"images={embedded_images} wikilinks={wikilinks} cross_vault_links={cross_links} "
        "broken_links=0 broken_anchors=0 control_character_files=0 "
        "source_hashes_unchanged=true manifests_mirrored=true"
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument("--write", action="store_true")
    modes.add_argument("--verify-only", action="store_true")
    args = parser.parse_args()
    return run(write=args.write)


