def parse_frontmatter(text: str) -> str:
    match = re.match(r"\A---\n(.*?)\n---\n", text, flags=re.DOTALL)
    return match.group(1) if match else ""


def resolve_wikilink(workspace: Path, raw_target: str) -> tuple[Path | None, str | None]:
    target = raw_target.split("|", 1)[0].strip()
    if not target or "://" in target:
        return None, None
    note, marker, anchor = target.partition("#")
    if not note:
        return None, anchor or None
    candidate = workspace / Path(note.replace("/", "\\"))
    if candidate.suffix.lower() != ".md":
        candidate = candidate.with_suffix(".md")
    return candidate, anchor if marker else None


def verify_card(workspace: Path, path: Path, name: str, card: dict[str, object]) -> list[str]:
    issues: list[str] = []
    if not path.is_file() or path.stat().st_size == 0:
        return [f"missing_or_empty:{path}"]
    text = path.read_text(encoding="utf-8")
    frontmatter = parse_frontmatter(text)
    if not frontmatter:
        issues.append(f"missing_frontmatter:{path}")
    if f'card_id: "{card["card_id"]}"' not in frontmatter:
        issues.append(f"card_id_mismatch:{path}")
    if f"disease_name: {yaml_flow(name)}" not in frontmatter:
        issues.append(f"disease_name_mismatch:{path}")
    for heading in REQUIRED_HEADINGS:
        count = sum(1 for line in text.splitlines() if line == f"# {heading}")
        if count != 1:
            issues.append(f"heading_count:{path}:{heading}:{count}")
    expected_source = source_target(str(card["source"]))
    if f"[[{expected_source}" not in text:
        issues.append(f"missing_source_link:{path}:{expected_source}")
    for raw in re.findall(r"\[\[([^\]]+)\]\]", text):
        candidate, anchor = resolve_wikilink(workspace, raw)
        if candidate is None:
            continue
        if not candidate.is_file():
            # Cross-vault study links are permitted and deliberately marked pending.
            if "/" not in raw.split("|", 1)[0]:
                continue
            issues.append(f"broken_link:{path}:{raw}")
            continue
        if anchor and candidate.stat().st_size:
            target_text = candidate.read_text(encoding="utf-8")
            headings = {
                re.sub(r"^#{1,6}\s+", "", line).strip()
                for line in target_text.splitlines()
                if re.match(r"^#{1,6}\s+", line)
            }
            if anchor not in headings:
                issues.append(f"broken_anchor:{path}:{raw}")
    return issues


